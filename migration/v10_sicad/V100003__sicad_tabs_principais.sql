CREATE TABLE SICAD_ESTRUTURAORG (
    ID_LOCAL NUMBER PRIMARY KEY,
    ID NUMBER(20),
    NOME VARCHAR2(250),
    SIGLA VARCHAR2(100),
    IDSUPERIOR NUMBER(20),
    SUPERIOR VARCHAR2(250),
    CORPORACAO VARCHAR2(250),
    CORPORACAOID NUMBER(20),
    TELEFONE VARCHAR2(200),
    TIPOESTRUTURAORG VARCHAR2(150),
    TIPOESTRUTURAORGID NUMBER(20),
    TIPOESTRUTURAORGNOME VARCHAR2(150)
);

CREATE SEQUENCE SICAD_ESTRUTURAORG_SQ
    START WITH 1
    INCREMENT BY 1
    NOMAXVALUE
    NOCACHE
    ORDER;

CREATE OR REPLACE TRIGGER SICAD_ESTRUTURAORG_TG
    BEFORE INSERT ON SICAD_ESTRUTURAORG
    FOR EACH ROW
BEGIN
    :NEW.ID_LOCAL := SICAD_ESTRUTURAORG_SQ.NEXTVAL;
END;
/



