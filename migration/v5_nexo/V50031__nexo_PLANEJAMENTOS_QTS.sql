CREATE TABLE NEXO_PLANEJAMENTOS_QTS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    CONVOCACAO_ID NUMBER(19, 0) NOT NULL,
    DATA_INICIO_SEMANA DATE NOT NULL,
    DATA_FIM_SEMANA DATE NOT NULL,
    SEMANA_ISO VARCHAR2(10) NOT NULL,
    NOME VARCHAR2(160) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'RASCUNHO' NOT NULL,
    VERSAO_ALGORITMO VARCHAR2(40) DEFAULT 'BASE_COORDENADA_V1' NOT NULL,
    GERADO_EM TIMESTAMP,
    APLICADO_EM TIMESTAMP,
    PUBLICADO_EM TIMESTAMP,
    OBSERVACAO VARCHAR2(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_PLAN_QTS_CONVOC FOREIGN KEY (CONVOCACAO_ID) REFERENCES NEXO_CONVOCACOES (ID),
    CONSTRAINT CK_NEXO_PLAN_QTS_STATUS CHECK (STATUS IN (
        'RASCUNHO', 'DIAGNOSTICADO', 'PROCESSANDO', 'EM_REVISAO',
        'APLICADO_PARCIAL', 'APLICADO', 'PUBLICADO_PARCIAL', 'PUBLICADO',
        'CANCELADO', 'FALHA'
    ))
);

CREATE TABLE NEXO_PLANEJAMENTOS_QTS_TURMAS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    PLANEJAMENTO_QTS_ID NUMBER(19, 0) NOT NULL,
    TURMA_ID NUMBER(19, 0) NOT NULL,
    CRONOGRAMA_ID NUMBER(19, 0),
    MODELO_HORARIO VARCHAR2(30) DEFAULT 'MODELO_C' NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'SELECIONADA' NOT NULL,
    PERCENTUAL_PREENCHIMENTO NUMBER(5, 2) DEFAULT 0 NOT NULL,
    NIVEL_CONFIANCA NUMBER(5, 2) DEFAULT 0 NOT NULL,
    TOTAL_ALERTAS NUMBER(10, 0) DEFAULT 0 NOT NULL,
    OBSERVACAO VARCHAR2(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_PLAN_QTS_TUR_PLAN FOREIGN KEY (PLANEJAMENTO_QTS_ID) REFERENCES NEXO_PLANEJAMENTOS_QTS (ID),
    CONSTRAINT FK_NEXO_PLAN_QTS_TUR_TURMA FOREIGN KEY (TURMA_ID) REFERENCES NEXO_TURMAS (ID),
    CONSTRAINT FK_NEXO_PLAN_QTS_TUR_CRON FOREIGN KEY (CRONOGRAMA_ID) REFERENCES NEXO_CRONOGRAMAS (ID),
    CONSTRAINT CK_NEXO_PLAN_QTS_TUR_STATUS CHECK (STATUS IN (
        'SELECIONADA', 'COM_ALERTAS', 'BLOQUEADA', 'SUGERIDA',
        'AJUSTADA', 'APROVADA', 'APLICADA', 'PUBLICADA', 'CANCELADA', 'FALHA'
    ))
);

CREATE TABLE NEXO_PLANEJAMENTOS_QTS_AULAS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    PLANEJAMENTO_QTS_ID NUMBER(19, 0) NOT NULL,
    PLANEJAMENTO_TURMA_ID NUMBER(19, 0) NOT NULL,
    TURMA_ID NUMBER(19, 0) NOT NULL,
    CRONOGRAMA_ID NUMBER(19, 0),
    CRONOGRAMA_AULA_ID NUMBER(19, 0),
    MODULO_ID NUMBER(19, 0),
    DOCENTE_ID NUMBER(19, 0),
    DATA_AULA DATE NOT NULL,
    HORA_INICIO VARCHAR2(5) NOT NULL,
    HORA_FIM VARCHAR2(5) NOT NULL,
    TURNO VARCHAR2(20),
    STATUS VARCHAR2(30) DEFAULT 'SUGERIDA' NOT NULL,
    MOTIVO_ESCOLHA VARCHAR2(500),
    ALERTA VARCHAR2(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_PLAN_QTS_AULA_PLAN FOREIGN KEY (PLANEJAMENTO_QTS_ID) REFERENCES NEXO_PLANEJAMENTOS_QTS (ID),
    CONSTRAINT FK_NEXO_PLAN_QTS_AULA_TURP FOREIGN KEY (PLANEJAMENTO_TURMA_ID) REFERENCES NEXO_PLANEJAMENTOS_QTS_TURMAS (ID),
    CONSTRAINT FK_NEXO_PLAN_QTS_AULA_TURMA FOREIGN KEY (TURMA_ID) REFERENCES NEXO_TURMAS (ID),
    CONSTRAINT FK_NEXO_PLAN_QTS_AULA_CRON FOREIGN KEY (CRONOGRAMA_ID) REFERENCES NEXO_CRONOGRAMAS (ID),
    CONSTRAINT FK_NEXO_PLAN_QTS_AULA_CRON_AULA FOREIGN KEY (CRONOGRAMA_AULA_ID) REFERENCES NEXO_CRONOGRAMA_AULAS (ID),
    CONSTRAINT FK_NEXO_PLAN_QTS_AULA_MOD FOREIGN KEY (MODULO_ID) REFERENCES NEXO_MODULOS_TEMATICOS (ID),
    CONSTRAINT FK_NEXO_PLAN_QTS_AULA_DOC FOREIGN KEY (DOCENTE_ID) REFERENCES NEXO_DOCENTES (ID),
    CONSTRAINT CK_NEXO_PLAN_QTS_AULA_STATUS CHECK (STATUS IN ('SUGERIDA', 'AJUSTADA', 'APLICADA', 'CANCELADA', 'FALHA'))
);

CREATE INDEX IDX_NEXO_PLAN_QTS_STATUS
    ON NEXO_PLANEJAMENTOS_QTS (CORPORACAO_ID, STATUS, ATIVO);

CREATE UNIQUE INDEX UK_NEXO_PLAN_QTS_ATIVO
    ON NEXO_PLANEJAMENTOS_QTS (CORPORACAO_ID, CONVOCACAO_ID, SEMANA_ISO, ATIVO);

CREATE INDEX IDX_NEXO_PLAN_QTS_TURMAS_PLAN
    ON NEXO_PLANEJAMENTOS_QTS_TURMAS (PLANEJAMENTO_QTS_ID, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_PLAN_QTS_TURMAS_TURMA
    ON NEXO_PLANEJAMENTOS_QTS_TURMAS (CORPORACAO_ID, TURMA_ID, ATIVO);

CREATE UNIQUE INDEX UK_NEXO_PLAN_QTS_TURMA_ATIVA
    ON NEXO_PLANEJAMENTOS_QTS_TURMAS (PLANEJAMENTO_QTS_ID, TURMA_ID, ATIVO);

CREATE INDEX IDX_NEXO_PLAN_QTS_AULAS_PLAN
    ON NEXO_PLANEJAMENTOS_QTS_AULAS (PLANEJAMENTO_QTS_ID, PLANEJAMENTO_TURMA_ID, ATIVO);

CREATE INDEX IDX_NEXO_PLAN_QTS_AULAS_DOC_DATA
    ON NEXO_PLANEJAMENTOS_QTS_AULAS (CORPORACAO_ID, DOCENTE_ID, DATA_AULA, HORA_INICIO, ATIVO);

CREATE INDEX IDX_NEXO_PLAN_QTS_AULAS_CRON
    ON NEXO_PLANEJAMENTOS_QTS_AULAS (CRONOGRAMA_ID, CRONOGRAMA_AULA_ID);

COMMENT ON TABLE NEXO_PLANEJAMENTOS_QTS IS 'Planejamento semanal coordenado para montagem de QTS por curso.';
COMMENT ON TABLE NEXO_PLANEJAMENTOS_QTS_TURMAS IS 'Turmas incluidas em um planejamento semanal coordenado de QTS.';
COMMENT ON TABLE NEXO_PLANEJAMENTOS_QTS_AULAS IS 'Sugestoes de aulas geradas pelo motor coordenado de QTS.';
