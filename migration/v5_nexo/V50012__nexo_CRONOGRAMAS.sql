CREATE TABLE NEXO_CRONOGRAMAS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    TURMA_ID NUMBER(19, 0) NOT NULL,
    MATRIZ_ID NUMBER(19, 0) NOT NULL,
    DATA_INICIO_SEMANA DATE NOT NULL,
    DATA_FIM_SEMANA DATE NOT NULL,
    SEMANA_ISO VARCHAR2(8) NOT NULL,
    NOME VARCHAR2(160) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'RASCUNHO' NOT NULL,
    OBSERVACAO VARCHAR2(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_CRON_TURMA FOREIGN KEY (TURMA_ID) REFERENCES NEXO_TURMAS (ID),
    CONSTRAINT FK_NEXO_CRON_MATRIZ FOREIGN KEY (MATRIZ_ID) REFERENCES NEXO_MATRIZES_CURRICULARES (ID),
    CONSTRAINT CK_NEXO_CRON_PERIODO CHECK (DATA_FIM_SEMANA >= DATA_INICIO_SEMANA),
    CONSTRAINT CK_NEXO_CRON_STATUS CHECK (STATUS IN ('RASCUNHO', 'EM_REVISAO', 'PUBLICADO', 'CANCELADO'))
);

CREATE INDEX IDX_NEXO_CRON_TURMA_SEMANA
    ON NEXO_CRONOGRAMAS (CORPORACAO_ID, TURMA_ID, SEMANA_ISO, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_CRON_MATRIZ
    ON NEXO_CRONOGRAMAS (CORPORACAO_ID, MATRIZ_ID, ATIVO);

CREATE INDEX IDX_NEXO_CRON_PERIODO
    ON NEXO_CRONOGRAMAS (CORPORACAO_ID, DATA_INICIO_SEMANA, DATA_FIM_SEMANA, ATIVO);
