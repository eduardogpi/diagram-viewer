CREATE TABLE NEXO_TOPICOS_TEMATICOS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    MODULO_TEMATICO_ID NUMBER(19, 0) NOT NULL,
    NOME VARCHAR2(240) NOT NULL,
    DESCRICAO VARCHAR2(500),
    CARGA_HORARIA_PRESENCIAL NUMBER(5, 0) DEFAULT 0 NOT NULL,
    CARGA_HORARIA_ASSINCRONA NUMBER(5, 0) DEFAULT 0 NOT NULL,
    CARGA_HORARIA_TOTAL NUMBER(5, 0) DEFAULT 0 NOT NULL,
    ORDEM NUMBER(10, 0) DEFAULT 0 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_TOPICO_MODULO FOREIGN KEY (MODULO_TEMATICO_ID) REFERENCES NEXO_MODULOS_TEMATICOS (ID),
    CONSTRAINT UK_NEXO_TOPICO_MOD_NOME UNIQUE (MODULO_TEMATICO_ID, NOME, ATIVO),
    CONSTRAINT CK_NEXO_TOPICO_CARGA_PRES CHECK (CARGA_HORARIA_PRESENCIAL >= 0),
    CONSTRAINT CK_NEXO_TOPICO_CARGA_ASS CHECK (CARGA_HORARIA_ASSINCRONA >= 0),
    CONSTRAINT CK_NEXO_TOPICO_CARGA_TOTAL CHECK (CARGA_HORARIA_TOTAL >= 0),
    CONSTRAINT CK_NEXO_TOPICO_CARGA_SOMA CHECK (CARGA_HORARIA_TOTAL = CARGA_HORARIA_PRESENCIAL + CARGA_HORARIA_ASSINCRONA)
);

CREATE INDEX IDX_NEXO_TOPICOS_MODULO
    ON NEXO_TOPICOS_TEMATICOS (MODULO_TEMATICO_ID, CORPORACAO_ID, ATIVO, ORDEM);

CREATE INDEX IDX_NEXO_TOPICOS_CORP
    ON NEXO_TOPICOS_TEMATICOS (CORPORACAO_ID, ATIVO);
