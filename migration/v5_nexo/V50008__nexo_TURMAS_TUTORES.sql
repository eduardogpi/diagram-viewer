CREATE TABLE NEXO_TURMAS_TUTORES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    TURMA_ID NUMBER(19, 0) NOT NULL,
    SSO_SERVIDOR_ID NUMBER(19, 0),
    CPF VARCHAR2(11) NOT NULL,
    NOME VARCHAR2(180) NOT NULL,
    EMAIL VARCHAR2(160),
    TELEFONE VARCHAR2(40),
    TIPO VARCHAR2(30) DEFAULT 'TUTOR' NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'ATIVO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_TURMA_TUTOR_TURMA FOREIGN KEY (TURMA_ID) REFERENCES NEXO_TURMAS (ID),
    CONSTRAINT UK_NEXO_TURMA_TUTOR_CPF UNIQUE (TURMA_ID, CPF, ATIVO),
    CONSTRAINT CK_NEXO_TURMA_TUTOR_CPF_LEN CHECK (LENGTH(CPF) = 11),
    CONSTRAINT CK_NEXO_TURMA_TUTOR_TIPO CHECK (TIPO IN ('TUTOR', 'COORDENADOR'))
);

CREATE INDEX IDX_NEXO_TURMA_TUTOR_TURMA
    ON NEXO_TURMAS_TUTORES (TURMA_ID, ATIVO, TIPO);

CREATE INDEX IDX_NEXO_TURMA_TUTOR_CORP_CPF
    ON NEXO_TURMAS_TUTORES (CORPORACAO_ID, CPF, ATIVO);
