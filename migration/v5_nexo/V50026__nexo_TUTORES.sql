CREATE TABLE NEXO_TUTORES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    SSO_SERVIDOR_ID NUMBER(19, 0),
    CPF VARCHAR2(11) NOT NULL,
    NOME VARCHAR2(180) NOT NULL,
    EMAIL VARCHAR2(160),
    TELEFONE VARCHAR2(40),
    OBSERVACAO VARCHAR2(500),
    STATUS VARCHAR2(30) DEFAULT 'ATIVO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_NEXO_TUTOR_CORP_CPF UNIQUE (CORPORACAO_ID, CPF, ATIVO),
    CONSTRAINT CK_NEXO_TUTOR_CPF_LEN CHECK (LENGTH(CPF) = 11),
    CONSTRAINT CK_NEXO_TUTOR_STATUS CHECK (STATUS IN ('ATIVO', 'INATIVO'))
);

CREATE INDEX IDX_NEXO_TUTORES_CORP_STATUS
    ON NEXO_TUTORES (CORPORACAO_ID, STATUS, ATIVO, NOME);

INSERT INTO NEXO_TUTORES (
    CORPORACAO_ID,
    SSO_SERVIDOR_ID,
    CPF,
    NOME,
    EMAIL,
    TELEFONE,
    STATUS,
    CRIADO_EM,
    ATUALIZADO_EM,
    ATIVO
)
SELECT
    CORPORACAO_ID,
    SSO_SERVIDOR_ID,
    CPF,
    NOME,
    EMAIL,
    TELEFONE,
    'ATIVO',
    CRIADO_EM,
    ATUALIZADO_EM,
    1
FROM (
    SELECT
        T.*,
        ROW_NUMBER() OVER (PARTITION BY T.CORPORACAO_ID, T.CPF ORDER BY T.ATUALIZADO_EM DESC, T.ID DESC) AS RN
    FROM NEXO_TURMAS_TUTORES T
    WHERE T.ATIVO = 1
      AND T.CPF IS NOT NULL
)
WHERE RN = 1;
