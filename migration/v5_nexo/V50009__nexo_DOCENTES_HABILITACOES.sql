CREATE TABLE NEXO_DOCENTES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    SSO_SERVIDOR_ID NUMBER(19, 0),
    CPF VARCHAR2(11) NOT NULL,
    NOME VARCHAR2(180) NOT NULL,
    EMAIL VARCHAR2(160),
    TELEFONE VARCHAR2(40),
    TITULACAO VARCHAR2(120),
    ESPECIALIZACAO VARCHAR2(240),
    OBSERVACAO VARCHAR2(500),
    STATUS VARCHAR2(30) DEFAULT 'ATIVO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_NEXO_DOCENTE_CORP_CPF UNIQUE (CORPORACAO_ID, CPF, ATIVO),
    CONSTRAINT CK_NEXO_DOCENTE_CPF_LEN CHECK (LENGTH(CPF) = 11),
    CONSTRAINT CK_NEXO_DOCENTE_STATUS CHECK (STATUS IN ('ATIVO', 'INATIVO', 'AFASTADO'))
);

CREATE TABLE NEXO_DOCENTES_HABILITACOES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    DOCENTE_ID NUMBER(19, 0) NOT NULL,
    MODULO_TEMATICO_ID NUMBER(19, 0) NOT NULL,
    TIPO_HABILITACAO VARCHAR2(30) DEFAULT 'MANUAL' NOT NULL,
    DOCUMENTO_REFERENCIA VARCHAR2(240),
    OBSERVACAO VARCHAR2(500),
    STATUS VARCHAR2(30) DEFAULT 'ATIVA' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_DOC_HAB_DOCENTE FOREIGN KEY (DOCENTE_ID) REFERENCES NEXO_DOCENTES (ID),
    CONSTRAINT FK_NEXO_DOC_HAB_MODULO FOREIGN KEY (MODULO_TEMATICO_ID) REFERENCES NEXO_MODULOS_TEMATICOS (ID),
    CONSTRAINT UK_NEXO_DOC_HAB_DOC_MOD UNIQUE (DOCENTE_ID, MODULO_TEMATICO_ID, ATIVO),
    CONSTRAINT CK_NEXO_DOC_HAB_TIPO CHECK (TIPO_HABILITACAO IN ('ESPECIALIZACAO', 'MANUAL', 'EXPERIENCIA', 'OUTRA')),
    CONSTRAINT CK_NEXO_DOC_HAB_STATUS CHECK (STATUS IN ('ATIVA', 'INATIVA'))
);

CREATE INDEX IDX_NEXO_DOCENTES_CORP_STATUS
    ON NEXO_DOCENTES (CORPORACAO_ID, STATUS, ATIVO, NOME);

CREATE INDEX IDX_NEXO_DOC_HAB_DOCENTE
    ON NEXO_DOCENTES_HABILITACOES (DOCENTE_ID, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_DOC_HAB_MODULO
    ON NEXO_DOCENTES_HABILITACOES (MODULO_TEMATICO_ID, CORPORACAO_ID, ATIVO, STATUS);
