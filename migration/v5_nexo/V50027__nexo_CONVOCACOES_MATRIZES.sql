CREATE TABLE NEXO_CONVOCACOES_MATRIZES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    CONVOCACAO_ID NUMBER(19, 0) NOT NULL,
    MATRIZ_ID NUMBER(19, 0) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'APLICADA' NOT NULL,
    OBSERVACAO VARCHAR2(500),
    APLICADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_CONV_MATRIZ_CONV FOREIGN KEY (CONVOCACAO_ID) REFERENCES NEXO_CONVOCACOES (ID),
    CONSTRAINT FK_NEXO_CONV_MATRIZ_MATRIZ FOREIGN KEY (MATRIZ_ID) REFERENCES NEXO_MATRIZES_CURRICULARES (ID),
    CONSTRAINT CK_NEXO_CONV_MATRIZ_STATUS CHECK (STATUS IN ('APLICADA', 'SUBSTITUIDA', 'CANCELADA'))
);

CREATE INDEX IDX_NEXO_CONV_MATRIZES_CONV
    ON NEXO_CONVOCACOES_MATRIZES (CONVOCACAO_ID, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_CONV_MATRIZES_MATRIZ
    ON NEXO_CONVOCACOES_MATRIZES (MATRIZ_ID, ATIVO);

CREATE INDEX IDX_NEXO_CONV_MATRIZES_CORP
    ON NEXO_CONVOCACOES_MATRIZES (CORPORACAO_ID, ATIVO, STATUS);

CREATE UNIQUE INDEX UK_NEXO_CONV_MATRIZ_ATIVA
    ON NEXO_CONVOCACOES_MATRIZES (CORPORACAO_ID, CONVOCACAO_ID, ATIVO, STATUS);

INSERT INTO NEXO_CONVOCACOES_MATRIZES (
    CORPORACAO_ID,
    CONVOCACAO_ID,
    MATRIZ_ID,
    STATUS,
    OBSERVACAO,
    APLICADA_EM,
    CRIADO_EM,
    ATUALIZADO_EM,
    ATIVO
)
SELECT
    CORPORACAO_ID,
    CONVOCACAO_ID,
    MATRIZ_ID,
    STATUS,
    OBSERVACAO,
    APLICADA_EM,
    CRIADO_EM,
    ATUALIZADO_EM,
    ATIVO
FROM (
    SELECT
        TM.CORPORACAO_ID,
        T.CONVOCACAO_ID,
        TM.MATRIZ_ID,
        TM.STATUS,
        TM.OBSERVACAO,
        TM.APLICADA_EM,
        TM.CRIADO_EM,
        TM.ATUALIZADO_EM,
        TM.ATIVO,
        ROW_NUMBER() OVER (
            PARTITION BY TM.CORPORACAO_ID, T.CONVOCACAO_ID
            ORDER BY TM.APLICADA_EM DESC, TM.ID DESC
        ) AS RN
    FROM NEXO_TURMAS_MATRIZES TM
    JOIN NEXO_TURMAS T ON T.ID = TM.TURMA_ID
    WHERE TM.ATIVO = 1
      AND TM.STATUS = 'APLICADA'
      AND T.ATIVO = 1
)
WHERE RN = 1;
