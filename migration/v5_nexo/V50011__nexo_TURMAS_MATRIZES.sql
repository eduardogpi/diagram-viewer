CREATE TABLE NEXO_TURMAS_MATRIZES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    TURMA_ID NUMBER(19, 0) NOT NULL,
    MATRIZ_ID NUMBER(19, 0) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'APLICADA' NOT NULL,
    OBSERVACAO VARCHAR2(500),
    APLICADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_TURMA_MATRIZ_TURMA FOREIGN KEY (TURMA_ID) REFERENCES NEXO_TURMAS (ID),
    CONSTRAINT FK_NEXO_TURMA_MATRIZ_MATRIZ FOREIGN KEY (MATRIZ_ID) REFERENCES NEXO_MATRIZES_CURRICULARES (ID),
    CONSTRAINT CK_NEXO_TURMA_MATRIZ_STATUS CHECK (STATUS IN ('APLICADA', 'SUBSTITUIDA', 'CANCELADA'))
);

CREATE INDEX IDX_NEXO_TURMAS_MATRIZES_TURMA
    ON NEXO_TURMAS_MATRIZES (TURMA_ID, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_TURMAS_MATRIZES_MATRIZ
    ON NEXO_TURMAS_MATRIZES (MATRIZ_ID, ATIVO);

CREATE INDEX IDX_NEXO_TURMAS_MATRIZES_CORP
    ON NEXO_TURMAS_MATRIZES (CORPORACAO_ID, ATIVO, STATUS);
