CREATE TABLE NEXO_DOCENTES_DISPONIBILIDADES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    DOCENTE_ID NUMBER(19, 0) NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM DATE NOT NULL,
    DIA_SEMANA NUMBER(1, 0) NOT NULL,
    HORA_INICIO VARCHAR2(5) NOT NULL,
    HORA_FIM VARCHAR2(5) NOT NULL,
    TURNO VARCHAR2(30),
    OBSERVACAO VARCHAR2(500),
    STATUS VARCHAR2(30) DEFAULT 'ATIVA' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_DOC_DISP_DOCENTE FOREIGN KEY (DOCENTE_ID) REFERENCES NEXO_DOCENTES (ID),
    CONSTRAINT CK_NEXO_DOC_DISP_DIA CHECK (DIA_SEMANA BETWEEN 1 AND 7),
    CONSTRAINT CK_NEXO_DOC_DISP_PERIODO CHECK (DATA_FIM >= DATA_INICIO),
    CONSTRAINT CK_NEXO_DOC_DISP_HORA_INI CHECK (REGEXP_LIKE(HORA_INICIO, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_NEXO_DOC_DISP_HORA_FIM CHECK (REGEXP_LIKE(HORA_FIM, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_NEXO_DOC_DISP_HORARIO CHECK (HORA_FIM > HORA_INICIO),
    CONSTRAINT CK_NEXO_DOC_DISP_TURNO CHECK (TURNO IS NULL OR TURNO IN ('MANHA', 'TARDE', 'NOITE', 'INTEGRAL', 'OUTRO')),
    CONSTRAINT CK_NEXO_DOC_DISP_STATUS CHECK (STATUS IN ('ATIVA', 'INATIVA'))
);

CREATE INDEX IDX_NEXO_DOC_DISP_DOCENTE
    ON NEXO_DOCENTES_DISPONIBILIDADES (DOCENTE_ID, ATIVO, STATUS, DATA_INICIO, DATA_FIM);

CREATE INDEX IDX_NEXO_DOC_DISP_PERIODO
    ON NEXO_DOCENTES_DISPONIBILIDADES (CORPORACAO_ID, ATIVO, STATUS, DATA_INICIO, DATA_FIM, DIA_SEMANA);
