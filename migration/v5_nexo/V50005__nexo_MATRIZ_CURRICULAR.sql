CREATE TABLE NEXO_MATRIZES_CURRICULARES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    NOME VARCHAR2(160) NOT NULL,
    DESCRICAO VARCHAR2(500),
    VERSAO VARCHAR2(40) DEFAULT '1.0' NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'RASCUNHO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_NEXO_MATRIZ_CORP_NOME_VER UNIQUE (CORPORACAO_ID, NOME, VERSAO)
);

CREATE TABLE NEXO_DISCIPLINAS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    MATRIZ_ID NUMBER(19, 0) NOT NULL,
    NOME VARCHAR2(160) NOT NULL,
    DESCRICAO VARCHAR2(500),
    ORDEM NUMBER(10, 0) DEFAULT 0 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_DISC_MATRIZ FOREIGN KEY (MATRIZ_ID) REFERENCES NEXO_MATRIZES_CURRICULARES (ID),
    CONSTRAINT UK_NEXO_DISC_MATRIZ_NOME UNIQUE (MATRIZ_ID, NOME)
);

CREATE TABLE NEXO_EIXOS_TEMATICOS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    DISCIPLINA_ID NUMBER(19, 0) NOT NULL,
    NOME VARCHAR2(160) NOT NULL,
    DESCRICAO VARCHAR2(500),
    ORDEM NUMBER(10, 0) DEFAULT 0 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_EIXO_DISC FOREIGN KEY (DISCIPLINA_ID) REFERENCES NEXO_DISCIPLINAS (ID),
    CONSTRAINT UK_NEXO_EIXO_DISC_NOME UNIQUE (DISCIPLINA_ID, NOME)
);

CREATE TABLE NEXO_MODULOS_TEMATICOS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    EIXO_TEMATICO_ID NUMBER(19, 0) NOT NULL,
    CODIGO VARCHAR2(40),
    NOME VARCHAR2(180) NOT NULL,
    DESCRICAO VARCHAR2(500),
    CARGA_HORARIA NUMBER(5, 0) NOT NULL,
    ORDEM NUMBER(10, 0) DEFAULT 0 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_MOD_EIXO FOREIGN KEY (EIXO_TEMATICO_ID) REFERENCES NEXO_EIXOS_TEMATICOS (ID),
    CONSTRAINT CK_NEXO_MOD_CARGA_HORARIA CHECK (CARGA_HORARIA >= 0),
    CONSTRAINT UK_NEXO_MOD_EIXO_NOME UNIQUE (EIXO_TEMATICO_ID, NOME)
);

CREATE INDEX IDX_NEXO_MATRIZES_CORP_ATIVO
    ON NEXO_MATRIZES_CURRICULARES (CORPORACAO_ID, ATIVO);

CREATE INDEX IDX_NEXO_DISC_MATRIZ
    ON NEXO_DISCIPLINAS (MATRIZ_ID, ATIVO, ORDEM);

CREATE INDEX IDX_NEXO_EIXOS_DISC
    ON NEXO_EIXOS_TEMATICOS (DISCIPLINA_ID, ATIVO, ORDEM);

CREATE INDEX IDX_NEXO_MOD_EIXO
    ON NEXO_MODULOS_TEMATICOS (EIXO_TEMATICO_ID, ATIVO, ORDEM);
