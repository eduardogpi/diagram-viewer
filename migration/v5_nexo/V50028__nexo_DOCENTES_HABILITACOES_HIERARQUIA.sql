ALTER TABLE NEXO_DOCENTES_HABILITACOES ADD (
    ESCOPO_TIPO VARCHAR2(30),
    DISCIPLINA_ID NUMBER(19, 0),
    EIXO_TEMATICO_ID NUMBER(19, 0)
);

UPDATE NEXO_DOCENTES_HABILITACOES
   SET ESCOPO_TIPO = 'MODULO_TEMATICO'
 WHERE ESCOPO_TIPO IS NULL;

ALTER TABLE NEXO_DOCENTES_HABILITACOES MODIFY (ESCOPO_TIPO VARCHAR2(30) NOT NULL);
ALTER TABLE NEXO_DOCENTES_HABILITACOES MODIFY (MODULO_TEMATICO_ID NULL);

ALTER TABLE NEXO_DOCENTES_HABILITACOES ADD CONSTRAINT FK_NEXO_DOC_HAB_DISCIPLINA
    FOREIGN KEY (DISCIPLINA_ID) REFERENCES NEXO_DISCIPLINAS (ID);

ALTER TABLE NEXO_DOCENTES_HABILITACOES ADD CONSTRAINT FK_NEXO_DOC_HAB_EIXO
    FOREIGN KEY (EIXO_TEMATICO_ID) REFERENCES NEXO_EIXOS_TEMATICOS (ID);

ALTER TABLE NEXO_DOCENTES_HABILITACOES ADD CONSTRAINT CK_NEXO_DOC_HAB_ESCOPO_TIPO
    CHECK (ESCOPO_TIPO IN ('DISCIPLINA', 'EIXO_TEMATICO', 'MODULO_TEMATICO'));

ALTER TABLE NEXO_DOCENTES_HABILITACOES ADD CONSTRAINT CK_NEXO_DOC_HAB_ESCOPO_REF CHECK (
    (ESCOPO_TIPO = 'DISCIPLINA' AND DISCIPLINA_ID IS NOT NULL AND EIXO_TEMATICO_ID IS NULL AND MODULO_TEMATICO_ID IS NULL)
    OR (ESCOPO_TIPO = 'EIXO_TEMATICO' AND DISCIPLINA_ID IS NULL AND EIXO_TEMATICO_ID IS NOT NULL AND MODULO_TEMATICO_ID IS NULL)
    OR (ESCOPO_TIPO = 'MODULO_TEMATICO' AND DISCIPLINA_ID IS NULL AND EIXO_TEMATICO_ID IS NULL AND MODULO_TEMATICO_ID IS NOT NULL)
);

CREATE INDEX IDX_NEXO_DOC_HAB_ESCOPO_DOC
    ON NEXO_DOCENTES_HABILITACOES (DOCENTE_ID, CORPORACAO_ID, ESCOPO_TIPO, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_DOC_HAB_DISCIPLINA
    ON NEXO_DOCENTES_HABILITACOES (DISCIPLINA_ID, CORPORACAO_ID, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_DOC_HAB_EIXO
    ON NEXO_DOCENTES_HABILITACOES (EIXO_TEMATICO_ID, CORPORACAO_ID, ATIVO, STATUS);
