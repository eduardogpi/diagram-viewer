CREATE TABLE NEXO_CONVOCACOES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    NOME VARCHAR2(160) NOT NULL,
    DESCRICAO VARCHAR2(500),
    ANO NUMBER(4, 0) NOT NULL,
    DATA_INICIO DATE,
    DATA_FIM DATE,
    STATUS VARCHAR2(30) DEFAULT 'RASCUNHO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_NEXO_CONV_CORP_NOME_ANO UNIQUE (CORPORACAO_ID, NOME, ANO),
    CONSTRAINT CK_NEXO_CONV_ANO CHECK (ANO >= 2000),
    CONSTRAINT CK_NEXO_CONV_DATAS CHECK (DATA_FIM IS NULL OR DATA_INICIO IS NULL OR DATA_FIM >= DATA_INICIO)
);

CREATE TABLE NEXO_ALUNOS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    CONVOCACAO_ID NUMBER(19, 0) NOT NULL,
    NOME VARCHAR2(180) NOT NULL,
    CPF VARCHAR2(11) NOT NULL,
    EMAIL VARCHAR2(160),
    TELEFONE VARCHAR2(40),
    STATUS VARCHAR2(30) DEFAULT 'CONVOCADO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_ALUNO_CONV FOREIGN KEY (CONVOCACAO_ID) REFERENCES NEXO_CONVOCACOES (ID),
    CONSTRAINT UK_NEXO_ALUNO_CONV_CPF UNIQUE (CONVOCACAO_ID, CPF),
    CONSTRAINT CK_NEXO_ALUNO_CPF_LEN CHECK (LENGTH(CPF) = 11)
);

CREATE INDEX IDX_NEXO_CONV_CORP_ATIVO
    ON NEXO_CONVOCACOES (CORPORACAO_ID, ATIVO, ANO);

CREATE INDEX IDX_NEXO_ALUNO_CONV_ATIVO
    ON NEXO_ALUNOS (CONVOCACAO_ID, ATIVO, NOME);

CREATE INDEX IDX_NEXO_ALUNO_CORP_CPF
    ON NEXO_ALUNOS (CORPORACAO_ID, CPF);
