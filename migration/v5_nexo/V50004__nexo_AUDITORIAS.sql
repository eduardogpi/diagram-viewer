CREATE TABLE NEXO_AUDITORIAS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    MODULO VARCHAR2(40) DEFAULT 'NEXO_ESPP' NOT NULL,
    ENTIDADE VARCHAR2(80) NOT NULL,
    ENTIDADE_ID NUMBER(19, 0),
    OPERACAO VARCHAR2(60) NOT NULL,
    DESCRICAO VARCHAR2(500),
    DADOS_ANTES CLOB,
    DADOS_DEPOIS CLOB,
    USUARIO_CPF VARCHAR2(11) NOT NULL,
    USUARIO_NOME VARCHAR2(180) NOT NULL,
    USUARIO_SERVIDOR_ID NUMBER(19, 0),
    IP_ORIGEM VARCHAR2(80),
    USER_AGENT VARCHAR2(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_NEXO_AUDITORIAS_CORP_DATA
    ON NEXO_AUDITORIAS (CORPORACAO_ID, CRIADO_EM);

CREATE INDEX IDX_NEXO_AUDITORIAS_ENTIDADE
    ON NEXO_AUDITORIAS (ENTIDADE, ENTIDADE_ID);
