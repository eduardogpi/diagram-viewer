CREATE TABLE NEXO_TURMAS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    CONVOCACAO_ID NUMBER(19, 0) NOT NULL,
    CODIGO VARCHAR2(40) NOT NULL,
    NOME VARCHAR2(160) NOT NULL,
    DESCRICAO VARCHAR2(500),
    CAPACIDADE NUMBER(5, 0),
    STATUS VARCHAR2(30) DEFAULT 'RASCUNHO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_TURMA_CONV FOREIGN KEY (CONVOCACAO_ID) REFERENCES NEXO_CONVOCACOES (ID),
    CONSTRAINT UK_NEXO_TURMA_CONV_COD UNIQUE (CONVOCACAO_ID, CODIGO),
    CONSTRAINT UK_NEXO_TURMA_CONV_NOME UNIQUE (CONVOCACAO_ID, NOME),
    CONSTRAINT CK_NEXO_TURMA_CAP CHECK (CAPACIDADE IS NULL OR CAPACIDADE >= 0)
);

CREATE TABLE NEXO_TURMAS_ALUNOS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    CONVOCACAO_ID NUMBER(19, 0) NOT NULL,
    TURMA_ID NUMBER(19, 0) NOT NULL,
    ALUNO_ID NUMBER(19, 0) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'MATRICULADO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_TURMA_ALUNO_CONV FOREIGN KEY (CONVOCACAO_ID) REFERENCES NEXO_CONVOCACOES (ID),
    CONSTRAINT FK_NEXO_TURMA_ALUNO_TURMA FOREIGN KEY (TURMA_ID) REFERENCES NEXO_TURMAS (ID),
    CONSTRAINT FK_NEXO_TURMA_ALUNO_ALUNO FOREIGN KEY (ALUNO_ID) REFERENCES NEXO_ALUNOS (ID),
    CONSTRAINT UK_NEXO_TURMA_ALUNO_TA_AT UNIQUE (TURMA_ID, ALUNO_ID, ATIVO),
    CONSTRAINT UK_NEXO_TURMA_ALUNO_CONV_AT UNIQUE (CONVOCACAO_ID, ALUNO_ID, ATIVO)
);

CREATE INDEX IDX_NEXO_TURMAS_CONV_ATIVO
    ON NEXO_TURMAS (CONVOCACAO_ID, ATIVO, CODIGO);

CREATE INDEX IDX_NEXO_TURMAS_CORP_ATIVO
    ON NEXO_TURMAS (CORPORACAO_ID, ATIVO);

CREATE INDEX IDX_NEXO_TURMAS_ALUNOS_TURMA
    ON NEXO_TURMAS_ALUNOS (TURMA_ID, ATIVO);

CREATE INDEX IDX_NEXO_TURMAS_ALUNOS_ALUNO
    ON NEXO_TURMAS_ALUNOS (ALUNO_ID, ATIVO);
