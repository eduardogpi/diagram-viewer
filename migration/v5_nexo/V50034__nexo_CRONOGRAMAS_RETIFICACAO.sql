ALTER TABLE NEXO_CRONOGRAMAS ADD (
    VERSAO NUMBER(10, 0) DEFAULT 1 NOT NULL,
    CRONOGRAMA_ORIGEM_ID NUMBER(19, 0),
    VERSAO_VIGENTE NUMBER(1, 0) DEFAULT 1 NOT NULL,
    TIPO_RETIFICACAO VARCHAR2(40),
    MOTIVO_RETIFICACAO VARCHAR2(500),
    PUBLICADO_EM TIMESTAMP,
    RETIFICADO_EM TIMESTAMP
);

ALTER TABLE NEXO_CRONOGRAMAS ADD CONSTRAINT FK_NEXO_CRON_ORIGEM
    FOREIGN KEY (CRONOGRAMA_ORIGEM_ID) REFERENCES NEXO_CRONOGRAMAS (ID);

ALTER TABLE NEXO_CRONOGRAMAS ADD CONSTRAINT CK_NEXO_CRON_VERSAO
    CHECK (VERSAO >= 1);

ALTER TABLE NEXO_CRONOGRAMAS ADD CONSTRAINT CK_NEXO_CRON_VIGENTE
    CHECK (VERSAO_VIGENTE IN (0, 1));

ALTER TABLE NEXO_CRONOGRAMAS DROP CONSTRAINT CK_NEXO_CRON_STATUS;

ALTER TABLE NEXO_CRONOGRAMAS ADD CONSTRAINT CK_NEXO_CRON_STATUS
    CHECK (STATUS IN (
        'RASCUNHO',
        'EM_REVISAO',
        'PUBLICADO',
        'RETIFICACAO_EM_EDICAO',
        'RETIFICACAO_EM_REVISAO',
        'RETIFICADO',
        'CANCELADO'
    ));

UPDATE NEXO_CRONOGRAMAS
   SET PUBLICADO_EM = ATUALIZADO_EM
 WHERE STATUS = 'PUBLICADO'
   AND PUBLICADO_EM IS NULL;

CREATE INDEX IDX_NEXO_CRON_ORIGEM_VERSAO
    ON NEXO_CRONOGRAMAS (CORPORACAO_ID, CRONOGRAMA_ORIGEM_ID, VERSAO, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_CRON_VIGENTE
    ON NEXO_CRONOGRAMAS (CORPORACAO_ID, TURMA_ID, SEMANA_ISO, VERSAO_VIGENTE, ATIVO, STATUS);

COMMENT ON COLUMN NEXO_CRONOGRAMAS.VERSAO IS 'Numero da versao oficial do QTS da turma na semana.';
COMMENT ON COLUMN NEXO_CRONOGRAMAS.CRONOGRAMA_ORIGEM_ID IS 'Cronograma publicado que originou uma retificacao.';
COMMENT ON COLUMN NEXO_CRONOGRAMAS.VERSAO_VIGENTE IS 'Indica se a versao e a vigente para consulta oficial.';
COMMENT ON COLUMN NEXO_CRONOGRAMAS.TIPO_RETIFICACAO IS 'Tipo operacional da retificacao: docente, modulo, horario, local ou outro.';
COMMENT ON COLUMN NEXO_CRONOGRAMAS.MOTIVO_RETIFICACAO IS 'Justificativa funcional para abertura da retificacao.';
COMMENT ON COLUMN NEXO_CRONOGRAMAS.PUBLICADO_EM IS 'Data e hora de publicacao oficial da versao.';
COMMENT ON COLUMN NEXO_CRONOGRAMAS.RETIFICADO_EM IS 'Data e hora em que a versao foi substituida por retificacao.';
