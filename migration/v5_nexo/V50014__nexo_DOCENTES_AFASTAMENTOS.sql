CREATE TABLE NEXO_DOCENTES_AFASTAMENTOS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    DOCENTE_ID NUMBER(19, 0) NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM DATE NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    MOTIVO VARCHAR2(500) NOT NULL,
    ORIGEM_SOLICITACAO VARCHAR2(30) NOT NULL,
    SOLICITANTE_SERVIDOR_ID NUMBER(19, 0),
    SOLICITANTE_CPF VARCHAR2(11),
    SOLICITANTE_NOME VARCHAR2(180),
    VALIDADO_POR_SERVIDOR_ID NUMBER(19, 0),
    VALIDADO_POR_CPF VARCHAR2(11),
    VALIDADO_POR_NOME VARCHAR2(180),
    VALIDADO_EM TIMESTAMP,
    OBSERVACAO_VALIDACAO VARCHAR2(500),
    JUSTIFICATIVA_QTS_PUBLICADO VARCHAR2(500),
    STATUS VARCHAR2(30) DEFAULT 'PENDENTE' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_DOC_AFAST_DOCENTE FOREIGN KEY (DOCENTE_ID) REFERENCES NEXO_DOCENTES (ID),
    CONSTRAINT CK_NEXO_DOC_AFAST_PERIODO CHECK (DATA_FIM >= DATA_INICIO),
    CONSTRAINT CK_NEXO_DOC_AFAST_TIPO CHECK (TIPO IN ('LICENCA', 'ATESTADO', 'MISSAO', 'FERIAS', 'IMPEDIMENTO', 'OUTRO')),
    CONSTRAINT CK_NEXO_DOC_AFAST_ORIGEM CHECK (ORIGEM_SOLICITACAO IN ('DOCENTE', 'GESTAO')),
    CONSTRAINT CK_NEXO_DOC_AFAST_STATUS CHECK (STATUS IN ('PENDENTE', 'APROVADO', 'REPROVADO', 'CANCELADO'))
);

CREATE INDEX IDX_NEXO_DOC_AFAST_DOCENTE
    ON NEXO_DOCENTES_AFASTAMENTOS (DOCENTE_ID, CORPORACAO_ID, ATIVO, STATUS, DATA_INICIO, DATA_FIM);

CREATE INDEX IDX_NEXO_DOC_AFAST_PERIODO
    ON NEXO_DOCENTES_AFASTAMENTOS (CORPORACAO_ID, ATIVO, STATUS, DATA_INICIO, DATA_FIM);
