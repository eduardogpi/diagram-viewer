CREATE TABLE NEXO_CRONOGRAMA_AULAS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    CRONOGRAMA_ID NUMBER(19, 0) NOT NULL,
    TURMA_ID NUMBER(19, 0) NOT NULL,
    MATRIZ_ID NUMBER(19, 0) NOT NULL,
    MODULO_ID NUMBER(19, 0) NOT NULL,
    DOCENTE_ID NUMBER(19, 0) NOT NULL,
    DATA_AULA DATE NOT NULL,
    DIA_SEMANA NUMBER(1, 0) NOT NULL,
    HORA_INICIO VARCHAR2(5) NOT NULL,
    HORA_FIM VARCHAR2(5) NOT NULL,
    CARGA_HORARIA NUMBER(4, 0) NOT NULL,
    LOCAL_AULA VARCHAR2(160),
    STATUS VARCHAR2(30) DEFAULT 'PREVISTA' NOT NULL,
    OBSERVACAO VARCHAR2(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_NEXO_AULA_CRON FOREIGN KEY (CRONOGRAMA_ID) REFERENCES NEXO_CRONOGRAMAS (ID),
    CONSTRAINT FK_NEXO_AULA_TURMA FOREIGN KEY (TURMA_ID) REFERENCES NEXO_TURMAS (ID),
    CONSTRAINT FK_NEXO_AULA_MATRIZ FOREIGN KEY (MATRIZ_ID) REFERENCES NEXO_MATRIZES_CURRICULARES (ID),
    CONSTRAINT FK_NEXO_AULA_MODULO FOREIGN KEY (MODULO_ID) REFERENCES NEXO_MODULOS_TEMATICOS (ID),
    CONSTRAINT FK_NEXO_AULA_DOCENTE FOREIGN KEY (DOCENTE_ID) REFERENCES NEXO_DOCENTES (ID),
    CONSTRAINT CK_NEXO_AULA_DIA CHECK (DIA_SEMANA BETWEEN 1 AND 7),
    CONSTRAINT CK_NEXO_AULA_HORA_INI CHECK (REGEXP_LIKE(HORA_INICIO, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_NEXO_AULA_HORA_FIM CHECK (REGEXP_LIKE(HORA_FIM, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_NEXO_AULA_HORARIO CHECK (HORA_FIM > HORA_INICIO),
    CONSTRAINT CK_NEXO_AULA_CARGA CHECK (CARGA_HORARIA > 0),
    CONSTRAINT CK_NEXO_AULA_STATUS CHECK (STATUS IN ('PREVISTA', 'REALIZADA', 'CANCELADA', 'REMARCADA'))
);

CREATE INDEX IDX_NEXO_AULA_CRONOGRAMA
    ON NEXO_CRONOGRAMA_AULAS (CORPORACAO_ID, CRONOGRAMA_ID, ATIVO, DATA_AULA, HORA_INICIO);

CREATE INDEX IDX_NEXO_AULA_TURMA_HORARIO
    ON NEXO_CRONOGRAMA_AULAS (CORPORACAO_ID, TURMA_ID, DATA_AULA, HORA_INICIO, HORA_FIM, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_AULA_DOCENTE_HORARIO
    ON NEXO_CRONOGRAMA_AULAS (CORPORACAO_ID, DOCENTE_ID, DATA_AULA, HORA_INICIO, HORA_FIM, ATIVO, STATUS);

CREATE INDEX IDX_NEXO_AULA_MODULO
    ON NEXO_CRONOGRAMA_AULAS (CORPORACAO_ID, MODULO_ID, ATIVO, STATUS);
