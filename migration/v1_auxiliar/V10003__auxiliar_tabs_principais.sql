CREATE TABLE AUX_CONFIGS_SISTEMA (
     ID NUMBER PRIMARY KEY,
     AMBIENTE VARCHAR2(4) DEFAULT NULL,
     AUDITS_ENDPOINTS VARCHAR2(4) DEFAULT NULL
);

CREATE SEQUENCE AUX_CONFIGS_SISTEMA_SQ
    START WITH 1
    INCREMENT BY 1
    NOMAXVALUE
    NOCACHE
    ORDER;

CREATE OR REPLACE TRIGGER AUX_CONFIGS_SISTEMA_TG
    BEFORE INSERT ON AUX_CONFIGS_SISTEMA
    FOR EACH ROW
BEGIN
    :NEW.ID := AUX_CONFIGS_SISTEMA_SQ.NEXTVAL;
END;
/

