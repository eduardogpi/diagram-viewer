CREATE TABLE AUX_UFS (
    ID NUMBER PRIMARY KEY,
    SCAD NUMBER(1),
    CODIGO NUMBER,
    SIGLA VARCHAR2(3),
    NOME VARCHAR2(100),
    REGIAO VARCHAR2(100),
    TIPO VARCHAR2(20)
);

CREATE SEQUENCE AUX_UFS_SQ
    START WITH 1
    INCREMENT BY 1
    NOMAXVALUE
    NOCACHE
    ORDER;

CREATE OR REPLACE TRIGGER AUX_UFS_TG
    BEFORE INSERT ON AUX_UFS
    FOR EACH ROW
BEGIN
    :NEW.ID := AUX_UFS_SQ.NEXTVAL;
END;
/

