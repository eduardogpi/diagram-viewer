CREATE TABLE AUX_EMAILS_STATUS_VERIFICACAO (
                           ID NUMBER PRIMARY KEY,
                           SCAD NUMBER(1),
                           CODIGO NUMBER,
                           DESCRICAO VARCHAR2(200),
                           ORDEM NUMBER
);

CREATE SEQUENCE AUX_EMAILS_STATUS_VERIFICACAO_SQ
    START WITH 1
    INCREMENT BY 1
    NOMAXVALUE
    NOCACHE
    ORDER;

CREATE OR REPLACE TRIGGER AUX_EMAILS_STATUS_VERIFICACAO_TG
    BEFORE INSERT ON AUX_EMAILS_STATUS_VERIFICACAO
    FOR EACH ROW
BEGIN
    :NEW.ID := AUX_EMAILS_STATUS_VERIFICACAO_SQ.NEXTVAL;
END;
/

