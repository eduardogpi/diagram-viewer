CREATE TABLE AUX_ANEXOS (
    ID NUMBER PRIMARY KEY,
    SCAD NUMBER(1),
    CORPORACAO_ID NUMBER,
    USUARIO_ID NUMBER,
    USUARIO_CPF VARCHAR2(30),
    NOME VARCHAR2(250),
    DESCRICAO VARCHAR2(500),
    MISSAO VARCHAR2(200),
    ANEXO_NOMEORI VARCHAR2(250),
    ANEXO_TIPO VARCHAR2(250),
    ANEXO_TAMANHO NUMBER,
    ANEXO_FILEWS_ID VARCHAR2(250),
    ANEXO_LINK_URL VARCHAR2(3000),
    DATA_HORA TIMESTAMP
);

CREATE SEQUENCE AUX_ANEXOS_SQ
    START WITH 1
    INCREMENT BY 1
    NOMAXVALUE
    NOCACHE
    ORDER;

CREATE OR REPLACE TRIGGER AUX_ANEXOS_TG
    BEFORE INSERT ON AUX_ANEXOS
    FOR EACH ROW
BEGIN
    :NEW.ID := AUX_ANEXOS_SQ.NEXTVAL;
END;
/

