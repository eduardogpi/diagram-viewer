CREATE TABLE AUX_IDENTIDADE_GENERO (
                           ID NUMBER PRIMARY KEY,
                           SCAD NUMBER(1),
                           CODIGO NUMBER,
                           DESCRICAO VARCHAR2(200),
                           ORDEM NUMBER
);

CREATE SEQUENCE AUX_IDENTIDADE_GENERO_SQ
    START WITH 1
    INCREMENT BY 1
    NOMAXVALUE
    NOCACHE
    ORDER;

CREATE OR REPLACE TRIGGER AUX_IDENTIDADE_GENERO_TG
    BEFORE INSERT ON AUX_IDENTIDADE_GENERO
    FOR EACH ROW
BEGIN
    :NEW.ID := AUX_IDENTIDADE_GENERO_SQ.NEXTVAL;
END;
/

