                           SCAD NUMBER(1),
                           CODIGO NUMBER,
                           DESCRICAO VARCHAR2(200),
                           ORDEM NUMBER
);

CREATE SEQUENCE AUX_ORIENTACAO_SEXUAL_SQ
    START WITH 1
    INCREMENT BY 1
    NOMAXVALUE
    NOCACHE
    ORDER;

CREATE OR REPLACE TRIGGER AUX_ORIENTACAO_SEXUAL_TG
    BEFORE INSERT ON AUX_ORIENTACAO_SEXUAL
    FOR EACH ROW
BEGIN
    :NEW.ID := AUX_ORIENTACAO_SEXUAL_SQ.NEXTVAL;
END;
/

