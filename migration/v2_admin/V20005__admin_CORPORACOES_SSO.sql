CREATE TABLE FORTIS_CORPORACOES_SSO (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SISTEMA_NOME VARCHAR2(60) DEFAULT 'FORTIS_ESPP' NOT NULL,
    CORPORACAO VARCHAR2(60) NOT NULL,
    AMBIENTE VARCHAR2(20) DEFAULT '*' NOT NULL,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    CORPORACAO_SIGLA VARCHAR2(30) NOT NULL,
    CORPORACAO_NOME VARCHAR2(180) NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_FORTIS_CORP_SSO UNIQUE (SISTEMA_NOME, CORPORACAO, AMBIENTE)
);

