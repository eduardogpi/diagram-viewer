CREATE TABLE FORTIS_SERVIDORES_ESPP (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    USUARIO_ID NUMBER(19, 0),
    CPF VARCHAR2(11) NOT NULL,
    NOME VARCHAR2(180) NOT NULL,
    EMAIL VARCHAR2(180),
    TELEFONE VARCHAR2(40),
    LOTACAO_ID NUMBER(19, 0),
    LOTACAO VARCHAR2(240),
    LOTACAO_SIGLA VARCHAR2(60),
    FUNCAO_INSTITUCIONAL VARCHAR2(180) NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM DATE,
    STATUS VARCHAR2(30) DEFAULT 'ATIVO' NOT NULL,
    ORIGEM VARCHAR2(30) DEFAULT 'MANUAL' NOT NULL,
    OBSERVACAO VARCHAR2(500),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_FORTIS_SERV_ESPP_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES FORTIS_USUARIOS (ID),
    CONSTRAINT UK_FORTIS_SERV_ESPP_CORP_CPF UNIQUE (CORPORACAO_ID, CPF),
    CONSTRAINT CK_FORTIS_SERV_ESPP_STATUS CHECK (STATUS IN ('ATIVO', 'INATIVO', 'AFASTADO', 'SUBSTITUTO')),
    CONSTRAINT CK_FORTIS_SERV_ESPP_ORIGEM CHECK (ORIGEM IN ('SICAD', 'SSO', 'MANUAL')),
    CONSTRAINT CK_FORTIS_SERV_ESPP_PERIODO CHECK (DATA_FIM IS NULL OR DATA_FIM >= DATA_INICIO)
);

CREATE INDEX IDX_FORTIS_SERV_ESPP_CORP_ATIVO_NOME
    ON FORTIS_SERVIDORES_ESPP (CORPORACAO_ID, ATIVO, NOME);

CREATE INDEX IDX_FORTIS_SERV_ESPP_CORP_STATUS
    ON FORTIS_SERVIDORES_ESPP (CORPORACAO_ID, STATUS);
