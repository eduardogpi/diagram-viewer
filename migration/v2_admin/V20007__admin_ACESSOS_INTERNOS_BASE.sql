-- Mantem as permissoes em catalogos para evitar regras escondidas no codigo.
CREATE TABLE FORTIS_CAPACIDADES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(240) NOT NULL,
    MODULO VARCHAR2(40) NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_FORTIS_CAPACIDADES_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_FORTIS_CAPACIDADES_TIPO CHECK (TIPO IN ('CONSULTA', 'ESCRITA', 'EXPORTACAO', 'ADMINISTRACAO')),
    CONSTRAINT CK_FORTIS_CAPACIDADES_ATIVO CHECK (ATIVO IN (0, 1))
);

CREATE TABLE FORTIS_ESCOPOS_ACESSO (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(30) NOT NULL,
    DESCRICAO VARCHAR2(180) NOT NULL,
    ORDEM_ABRANGENCIA NUMBER(5, 0) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_FORTIS_ESCOPOS_ACESSO_COD UNIQUE (CODIGO),
    CONSTRAINT CK_FORTIS_ESCOPOS_ORDEM CHECK (ORDEM_ABRANGENCIA >= 0),
    CONSTRAINT CK_FORTIS_ESCOPOS_ATIVO CHECK (ATIVO IN (0, 1))
);

-- Relaciona cada perfil com os acessos herdados pelo servidor.
CREATE TABLE FORTIS_PERFIS_CAPACIDADES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERFIL_ID NUMBER(19, 0) NOT NULL,
    CAPACIDADE_ID NUMBER(19, 0) NOT NULL,
    ESCOPO_ID NUMBER(19, 0) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_FORTIS_PERFCAP_PERFIL FOREIGN KEY (PERFIL_ID) REFERENCES FORTIS_PERFIS (ID),
    CONSTRAINT FK_FORTIS_PERFCAP_CAP FOREIGN KEY (CAPACIDADE_ID) REFERENCES FORTIS_CAPACIDADES (ID),
    CONSTRAINT FK_FORTIS_PERFCAP_ESCOPO FOREIGN KEY (ESCOPO_ID) REFERENCES FORTIS_ESCOPOS_ACESSO (ID),
    CONSTRAINT CK_FORTIS_PERFCAP_ATIVO CHECK (ATIVO IN (0, 1))
);

-- Permite preparar perfis antes do primeiro login do servidor.
CREATE TABLE FORTIS_SERVIDORES_ESPP_PERFIS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    SERVIDOR_ESPP_ID NUMBER(19, 0) NOT NULL,
    PERFIL_ID NUMBER(19, 0) NOT NULL,
    JUSTIFICATIVA VARCHAR2(500) NOT NULL,
    CRIADO_POR_USUARIO_ID NUMBER(19, 0),
    REVOGADO_POR_USUARIO_ID NUMBER(19, 0),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    REVOGADO_EM TIMESTAMP,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_FORTIS_SERVPERF_SERV FOREIGN KEY (SERVIDOR_ESPP_ID) REFERENCES FORTIS_SERVIDORES_ESPP (ID),
    CONSTRAINT FK_FORTIS_SERVPERF_PERFIL FOREIGN KEY (PERFIL_ID) REFERENCES FORTIS_PERFIS (ID),
    CONSTRAINT FK_FORTIS_SERVPERF_CRIADOR FOREIGN KEY (CRIADO_POR_USUARIO_ID) REFERENCES FORTIS_USUARIOS (ID),
    CONSTRAINT FK_FORTIS_SERVPERF_REVOGADOR FOREIGN KEY (REVOGADO_POR_USUARIO_ID) REFERENCES FORTIS_USUARIOS (ID),
    CONSTRAINT CK_FORTIS_SERVPERF_ATIVO CHECK (ATIVO IN (0, 1))
);

-- Registra excecoes concedidas ou revogadas para um servidor especifico.
CREATE TABLE FORTIS_SERVIDORES_ESPP_CAPACIDADES (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORPORACAO_ID NUMBER(10, 0) NOT NULL,
    SERVIDOR_ESPP_ID NUMBER(19, 0) NOT NULL,
    CAPACIDADE_ID NUMBER(19, 0) NOT NULL,
    ESCOPO_ID NUMBER(19, 0) NOT NULL,
    EFEITO VARCHAR2(20) NOT NULL,
    REFERENCIA_TIPO VARCHAR2(30),
    REFERENCIA_ID NUMBER(19, 0),
    JUSTIFICATIVA VARCHAR2(500) NOT NULL,
    CRIADO_POR_USUARIO_ID NUMBER(19, 0),
    REVOGADO_POR_USUARIO_ID NUMBER(19, 0),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    REVOGADO_EM TIMESTAMP,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_FORTIS_SERVCAP_SERV FOREIGN KEY (SERVIDOR_ESPP_ID) REFERENCES FORTIS_SERVIDORES_ESPP (ID),
    CONSTRAINT FK_FORTIS_SERVCAP_CAP FOREIGN KEY (CAPACIDADE_ID) REFERENCES FORTIS_CAPACIDADES (ID),
    CONSTRAINT FK_FORTIS_SERVCAP_ESCOPO FOREIGN KEY (ESCOPO_ID) REFERENCES FORTIS_ESCOPOS_ACESSO (ID),
    CONSTRAINT FK_FORTIS_SERVCAP_CRIADOR FOREIGN KEY (CRIADO_POR_USUARIO_ID) REFERENCES FORTIS_USUARIOS (ID),
    CONSTRAINT FK_FORTIS_SERVCAP_REVOGADOR FOREIGN KEY (REVOGADO_POR_USUARIO_ID) REFERENCES FORTIS_USUARIOS (ID),
    CONSTRAINT CK_FORTIS_SERVCAP_EFEITO CHECK (EFEITO IN ('CONCEDER', 'REVOGAR')),
    CONSTRAINT CK_FORTIS_SERVCAP_REF_TIPO CHECK (REFERENCIA_TIPO IS NULL OR REFERENCIA_TIPO IN ('TURMA', 'MODULO', 'CONVOCACAO')),
    CONSTRAINT CK_FORTIS_SERVCAP_REF CHECK (
        (REFERENCIA_TIPO IS NULL AND REFERENCIA_ID IS NULL)
        OR (REFERENCIA_TIPO IS NOT NULL AND REFERENCIA_ID IS NOT NULL)
    ),
    CONSTRAINT CK_FORTIS_SERVCAP_ATIVO CHECK (ATIVO IN (0, 1))
);

