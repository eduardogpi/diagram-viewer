CREATE TABLE FORTIS_USUARIOS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SSO_SERVIDOR_ID NUMBER(19, 0),
    CPF VARCHAR2(11) NOT NULL,
    NOME VARCHAR2(180) NOT NULL,
    EMAIL VARCHAR2(180),
    CORPORACAO VARCHAR2(60),
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ULTIMO_ACESSO_EM TIMESTAMP,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_FORTIS_USUARIOS_CPF UNIQUE (CPF)
);

CREATE TABLE FORTIS_PERFIS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(60) NOT NULL,
    DESCRICAO VARCHAR2(180) NOT NULL,
    MODULO VARCHAR2(40) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_FORTIS_PERFIS_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE FORTIS_USUARIOS_PERFIS (
    ID NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER(19, 0) NOT NULL,
    PERFIL_ID NUMBER(19, 0) NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_FORTIS_USUPERF_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES FORTIS_USUARIOS (ID),
    CONSTRAINT FK_FORTIS_USUPERF_PERFIL FOREIGN KEY (PERFIL_ID) REFERENCES FORTIS_PERFIS (ID),
    CONSTRAINT UK_FORTIS_USUPERF UNIQUE (USUARIO_ID, PERFIL_ID)
);

