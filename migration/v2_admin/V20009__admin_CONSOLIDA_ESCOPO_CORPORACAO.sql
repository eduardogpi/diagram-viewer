-- Consolida o antigo escopo GLOBAL no escopo CORPORACAO.
UPDATE FORTIS_PERFIS_CAPACIDADES
   SET ESCOPO_ID = (SELECT ID FROM FORTIS_ESCOPOS_ACESSO WHERE CODIGO = 'CORPORACAO')
 WHERE ESCOPO_ID = (SELECT ID FROM FORTIS_ESCOPOS_ACESSO WHERE CODIGO = 'GLOBAL');

UPDATE FORTIS_SERVIDORES_ESPP_CAPACIDADES
   SET ESCOPO_ID = (SELECT ID FROM FORTIS_ESCOPOS_ACESSO WHERE CODIGO = 'CORPORACAO')
 WHERE ESCOPO_ID = (SELECT ID FROM FORTIS_ESCOPOS_ACESSO WHERE CODIGO = 'GLOBAL');

UPDATE FORTIS_ESCOPOS_ACESSO
   SET DESCRICAO = 'Registros da corporacao do servidor',
       ORDEM_ABRANGENCIA = 50,
       ATUALIZADO_EM = CURRENT_TIMESTAMP
 WHERE CODIGO = 'CORPORACAO';

UPDATE FORTIS_ESCOPOS_ACESSO
   SET ATIVO = 0,
       DESCRICAO = 'Escopo descontinuado. Utilize CORPORACAO.',
       ATUALIZADO_EM = CURRENT_TIMESTAMP
 WHERE CODIGO = 'GLOBAL';
