ALTER TABLE FORTIS_USUARIOS ADD CORPORACAO_ID NUMBER(10, 0) DEFAULT 0;
ALTER TABLE FORTIS_USUARIOS ADD CORPORACAO_SIGLA VARCHAR2(30) DEFAULT 'NAO_INFORMADA';
ALTER TABLE FORTIS_USUARIOS ADD CORPORACAO_NOME VARCHAR2(180) DEFAULT 'CORPORACAO NAO INFORMADA';

UPDATE FORTIS_USUARIOS
   SET CORPORACAO_ID = CASE
           WHEN UPPER(CORPORACAO) IN ('SEAP', 'DGPP') THEN 7
           WHEN UPPER(CORPORACAO) = 'SPTC' THEN 5
           ELSE 0
       END,
       CORPORACAO_SIGLA = CASE
           WHEN UPPER(CORPORACAO) IN ('SEAP', 'DGPP') THEN 'DGPP'
           WHEN UPPER(CORPORACAO) = 'SPTC' THEN 'SPTC'
           ELSE NVL(UPPER(CORPORACAO), 'NAO_INFORMADA')
       END,
       CORPORACAO_NOME = CASE
           WHEN UPPER(CORPORACAO) IN ('SEAP', 'DGPP') THEN 'DIRETORIA GERAL DE ADMINISTRACAO PENITENCIARIA DO ESTADO DE GOIAS'
           WHEN UPPER(CORPORACAO) = 'SPTC' THEN 'SUPERINTENDENCIA DE POLICIA TECNICO-CIENTIFICA DO ESTADO DE GOIAS'
           ELSE 'CORPORACAO NAO MAPEADA'
       END;

ALTER TABLE FORTIS_USUARIOS MODIFY CORPORACAO_ID NOT NULL;
ALTER TABLE FORTIS_USUARIOS MODIFY CORPORACAO_SIGLA NOT NULL;
ALTER TABLE FORTIS_USUARIOS MODIFY CORPORACAO_NOME NOT NULL;

ALTER TABLE FORTIS_USUARIOS DROP CONSTRAINT UK_FORTIS_USUARIOS_CPF;
ALTER TABLE FORTIS_USUARIOS ADD CONSTRAINT UK_FORTIS_USUARIOS_CORP_CPF UNIQUE (CORPORACAO_ID, CPF);
