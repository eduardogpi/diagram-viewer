CREATE TABLE ADMIN_DADOSSYS (
    ID NUMBER PRIMARY KEY,
    VERSAO_COD VARCHAR2(20),
    SISTEMA_VERSAO VARCHAR2(20),
    SISTEMA_NOME VARCHAR2(250),
    SISTEMA_DESCRICAO VARCHAR2(3000),
    SISTEMA_FINALIDADE CLOB,
    DIR_MIN VARCHAR2(150),
    DIR_NM VARCHAR2(150),
    DIR_PC VARCHAR2(150),
    DIR_MAI VARCHAR2(150),
    PERFIL_SSO VARCHAR2(150)
);

CREATE SEQUENCE ADMIN_DADOSSYS_SQ
    START WITH 1
    INCREMENT BY 1
    NOMAXVALUE
    NOCACHE
    ORDER;

CREATE OR REPLACE TRIGGER ADMIN_DADOSSYS_TG
    BEFORE INSERT ON ADMIN_DADOSSYS
    FOR EACH ROW
BEGIN
    :NEW.ID := ADMIN_DADOSSYS_SQ.NEXTVAL;
END;
/

